const DICTS = { zh: zh, en: en };

// ---------- 语言状态 ----------
let _lang = null; // null = 尚未初始化

function detectLang() {
  try {
    const nav = typeof navigator !== 'undefined' ? navigator : null;
    const tag = nav && (nav.language || (nav.languages && nav.languages[0])) || '';
    return /^zh/i.test(tag) ? 'zh' : 'en';
  } catch (e) {
    return 'zh';
  }
}

function applyTitle() {
  try {
    if (typeof document !== 'undefined' && document.title !== undefined) {
      document.title = _lang === 'en' ? 'Time Buyer — open-source life simulator' : '时间买手 · 开源人生模拟器';
    }
  } catch (e) { /* 非浏览器环境忽略 */ }
}

export function initLang() {
  if (_lang) {
    return _lang;
  }
  let saved = null;
  try {
    const ttApi = getTT();
    if (ttApi && ttApi.getStorageSync) {
      const raw = ttApi.getStorageSync(LANG_KEY);
      if (raw === 'zh' || raw === 'en') {
        saved = raw;
      }
    }
  } catch (e) { /* 存储不可用则回退自动检测 */ }
  _lang = saved || detectLang();
  applyTitle();
  return _lang;
}

export function getLang() {
  return initLang();
}

export function isEnglish() {
  return getLang() === 'en';
}

export function setLang(next) {
  _lang = next === 'en' ? 'en' : 'zh';
  try {
    const ttApi = getTT();
    if (ttApi && ttApi.setStorageSync) {
      ttApi.setStorageSync(LANG_KEY, _lang);
    }
  } catch (e) { /* 存不下就算了，本次会话仍生效 */ }
  clearWrapCache(); // 关键：换行测量缓存按文本内容为键，换语言必须清空
  applyTitle();
  return _lang;
}

export function toggleLang() {
  return setLang(getLang() === 'en' ? 'zh' : 'en');
}

export function t(key, params) {
  const lang = getLang();
  let s = DICTS[lang][key];
  if (s === undefined) {
    s = DICTS.zh[key];
  }
  if (s === undefined) {
    return key; // 缺词条时暴露 key 本身——冒烟测试可扫描兜底
  }
  if (params) {
    Object.keys(params).forEach(function (k) {
      s = s.split('{' + k + '}').join(params[k]);
    });
  }
  return s;
}

// 数字 + 单位"天"的本地化（en 用紧凑 "d"，避免价格标签撑爆）
export function fmtDays(n) {
  return t('day.val', { n: n });
}
